const dicts: Record<string, Dict> = { id, en };

export type Lang = 'id' | 'en';

interface I18n { lang: Lang; t: (k: string) => string; setLang: (l: Lang) => void }

const Ctx = createContext<I18n>({ lang: 'id', t: (k) => id[k] ?? k, setLang: () => {} });

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>('id');
  useEffect(() => {
    const saved = localStorage.getItem('lang');
    if (saved === 'en' || saved === 'id') setLangState(saved);
  }, []);
  const setLang = (l: Lang) => {
    setLangState(l);
    localStorage.setItem('lang', l);
  };
  const t = (k: string) => dicts[lang][k] ?? id[k] ?? k;
  return <Ctx.Provider value={{ lang, t, setLang }}>{children}</Ctx.Provider>;
}

export const useI18n = (): I18n => useContext(Ctx);
